#!/usr/bin/env sh
# Meshwork — one-command installer for the Meshwork web workspace (app/).
#
#   curl -fsSL https://raw.githubusercontent.com/payswapdotorg/MeshWork/main/install.sh | sh
#
# Modelled on the ZCode distribution installer: fetch the source, set the app
# up under a Meshwork home directory and drop a `meshwork` command on PATH.
# Safe to re-run — the existing .env, database, dependencies and builds are
# carried across reinstalls and updates.
#
# Requirements: git + curl, plus Bun 1.1+ or Node.js 20+ (Bun is installed
# automatically when neither is present, unless MESHWORK_NO_BUN_INSTALL=1).
#
# Environment overrides (same naming pattern as the ZCode installer):
#   MESHWORK_REPO            git remote to clone from
#   MESHWORK_REF             branch or tag to install       (default: main)
#   MESHWORK_HOME            install root                   (default: ~/.meshwork)
#   MESHWORK_BIN_DIR         command directory              (default: ~/.local/bin)
#   MESHWORK_PORT            default port for `meshwork start` (default: 3000)
#   MESHWORK_NO_BUN_INSTALL  set to 1 to never auto-install Bun
set -eu

MESHWORK_REPO="${MESHWORK_REPO:-https://github.com/payswapdotorg/MeshWork.git}"
MESHWORK_REF="${MESHWORK_REF:-main}"
MESHWORK_HOME="${MESHWORK_HOME:-$HOME/.meshwork}"
MESHWORK_BIN_DIR="${MESHWORK_BIN_DIR:-$HOME/.local/bin}"
MESHWORK_PORT="${MESHWORK_PORT:-3000}"

say() { printf '\033[1;36m▸ %s\033[0m\n' "$1"; }
die() { printf '\033[1;31meshwork install: %s\033[0m\n' "$1" >&2; exit 1; }

need_cmd() {
  if ! command -v "$1" >/dev/null 2>&1; then
    die "requires $1. Install it and re-run this script."
  fi
}

need_cmd git
need_cmd curl

# --- runtime ------------------------------------------------------------------
# The app runs on Bun (preferred) or Node.js 20+. When neither is present we
# install Bun with its official script — the same runtime app/setup.sh uses.
find_runtime() {
  if command -v bun >/dev/null 2>&1; then
    echo bun
    return 0
  fi
  if command -v node >/dev/null 2>&1; then
    node_major="$(node --version | sed 's/^v\([0-9]*\).*/\1/')"
    if [ "${node_major:-0}" -ge 20 ]; then
      echo node
      return 0
    fi
  fi
  echo none
}

RUNTIME="$(find_runtime)"
if [ "$RUNTIME" = "none" ]; then
  if [ "${MESHWORK_NO_BUN_INSTALL:-0}" = "1" ]; then
    die "no Bun 1.1+ or Node.js 20+ found, and Bun auto-install is disabled."
  fi
  say "No Bun or Node.js 20+ found — installing Bun (official script, ~/.bun)"
  curl -fsSL https://bun.sh/install | sh >/dev/null
  BUN_BIN="$HOME/.bun/bin"
  if [ -x "$BUN_BIN/bun" ]; then
    PATH="$BUN_BIN:$PATH"
    export PATH
  else
    die "Bun installation did not produce ~/.bun/bin/bun"
  fi
fi

# --- fetch source ---------------------------------------------------------------
say "Fetching Meshwork ($MESHWORK_REF) — app/ only (sparse clone)"
STAGE="$MESHWORK_HOME/.stage"
rm -rf "$STAGE"
mkdir -p "$STAGE"

git clone --depth 1 --filter=blob:none --sparse --branch "$MESHWORK_REF" \
  "$MESHWORK_REPO" "$STAGE/src" >/dev/null 2>&1 || die "git clone failed"
git -C "$STAGE/src" sparse-checkout set app >/dev/null 2>&1 || die "sparse checkout failed"
[ -f "$STAGE/src/app/setup.sh" ] || die "the '$MESHWORK_REF' ref has no app/ workspace"

# --- swap in, preserving user data ----------------------------------------------
# The sparse clone (repo root incl. .git, with app/ checked out) becomes
# $MESHWORK_HOME/src, so `meshwork update` can fetch/reset in place. User
# state inside app/ (.env, db, node_modules, .next) is carried across.
APP_ROOT="$MESHWORK_HOME/src"
APP_SRC="$APP_ROOT/app"
if [ -d "$APP_ROOT" ]; then
  say "Existing installation found — preserving .env, database and dependencies"
  mv "$APP_ROOT" "$STAGE/old"
fi
mkdir -p "$MESHWORK_HOME"
mv "$STAGE/src" "$APP_ROOT"

if [ -d "$STAGE/old/app" ]; then
  if [ -f "$STAGE/old/app/.env" ]; then cp "$STAGE/old/app/.env" "$APP_SRC/.env"; fi
  if [ -d "$STAGE/old/app/db" ]; then mv "$STAGE/old/app/db" "$APP_SRC/db"; fi
  if [ -d "$STAGE/old/app/node_modules" ]; then mv "$STAGE/old/app/node_modules" "$APP_SRC/node_modules"; fi
  if [ -d "$STAGE/old/app/.next" ]; then mv "$STAGE/old/app/.next" "$APP_SRC/.next"; fi
fi

# --- app setup (deps + .env + database) -------------------------------------------
say "Setting up the workspace (dependencies, .env, database schema)"
( cd "$APP_SRC" && ./setup.sh )

# --- `meshwork` command -------------------------------------------------------------
say "Installing the meshwork command"
mkdir -p "$MESHWORK_BIN_DIR"
cat > "$MESHWORK_BIN_DIR/meshwork" <<LAUNCHER
#!/usr/bin/env sh
# meshwork — launcher for the Meshwork web workspace (generated by install.sh)
set -eu

# The Bun installer may only be on PATH in fresh shells after rc reload.
if [ -x "\$HOME/.bun/bin/bun" ]; then
  PATH="\$HOME/.bun/bin:\$PATH"
fi

MESHWORK_HOME="\${MESHWORK_HOME:-$MESHWORK_HOME}"
MESHWORK_REF="\${MESHWORK_REF:-$MESHWORK_REF}"
APP_DIR="\$MESHWORK_HOME/src/app"
GIT_ROOT="\$MESHWORK_HOME/src"
PID_FILE="\$MESHWORK_HOME/meshwork.pid"
LOG_FILE="\$MESHWORK_HOME/meshwork.log"
PORT="\${MESHWORK_PORT:-$MESHWORK_PORT}"

say() { printf '\033[1;36m▸ %s\033[0m\n' "\$1"; }
die() { printf '\033[1;31meshwork: %s\033[0m\n' "\$1" >&2; exit 1; }

pm() { command -v bun >/dev/null 2>&1 && echo bun || echo npm; }
# Resolve the JS runtime: "bun" or the node path. Invoking the real script
# files (not their env-node shims) keeps it working with Bun-only installs.
js_runtime() {
  if command -v bun >/dev/null 2>&1; then
    printf '%s' bun
  else
    command -v node
  fi
}
running() {
  [ -f "\$PID_FILE" ] && kill -0 "\$(cat "\$PID_FILE")" 2>/dev/null
}

usage() {
  cat <<USAGE
meshwork — Meshwork web workspace

  meshwork start [--port N] [--dev] [--build]   start the workspace
      production build on port $MESHWORK_PORT by default; --dev for the dev
      server, --build to force a production rebuild first
  meshwork stop                                 stop the workspace
  meshwork restart [--port N] [--dev] [--build] restart the workspace
  meshwork status                               running state + port
  meshwork logs                                 follow the server log
  meshwork update                               update source and rebuild
  meshwork doctor                               health check
  meshwork open                                 open the workspace in a browser
USAGE
}

cmd_start() {
  DEV=0
  FORCE_BUILD=0
  while [ \$# -gt 0 ]; do
    case "\$1" in
      --dev) DEV=1 ;;
      --build) FORCE_BUILD=1 ;;
      --port)
        [ \$# -ge 2 ] || die "--port needs a value"
        PORT="\$2"
        shift
        ;;
      *) die "unknown option: \$1 (try: meshwork help)" ;;
    esac
    shift
  done
  cd "\$APP_DIR"
  [ -f .env ] || cp .env.example .env
  if [ ! -d node_modules ]; then
    say "Installing dependencies"
    "\$(pm)" install
  fi
  if [ ! -f db/custom.db ]; then
    say "Creating the database"
    "\$(pm)" run db:push
  fi
  if running; then
    die "already running (pid \$(cat "\$PID_FILE")). Use: meshwork stop | restart"
  fi

  if [ "\$DEV" = "1" ]; then
    say "Starting the dev server on port \$PORT"
    nohup "\$(js_runtime)" node_modules/next/dist/bin/next dev -p "\$PORT" \\
      >"\$LOG_FILE" 2>&1 &
    echo \$! >"\$PID_FILE"
    say "Dev server starting — the first page load compiles, watch: meshwork logs"
    printf '    http://localhost:%s\n' "\$PORT"
    return 0
  fi

  if [ "\$FORCE_BUILD" = "1" ] || [ ! -f .next/standalone/server.js ]; then
    say "Building the production server (once per update)"
    "\$(pm)" run build
  fi
  say "Starting Meshwork on port \$PORT"
  PORT="\$PORT" NODE_ENV=production nohup "\$(js_runtime)" .next/standalone/server.js >"\$LOG_FILE" 2>&1 &
  echo \$! >"\$PID_FILE"

  i=0
  while [ "\$i" -lt 60 ]; do
    if ! kill -0 "\$(cat "\$PID_FILE")" 2>/dev/null; then
      say "The server exited early — the log explains: meshwork logs"
      return 1
    fi
    if curl -fsS -o /dev/null "http://127.0.0.1:\$PORT/" 2>/dev/null; then
      say "Meshwork is ready"
      printf '    http://localhost:%s\n' "\$PORT"
      return 0
    fi
    sleep 1
    i=\$((i + 1))
  done
  say "Still starting after 60s — the log explains: meshwork logs"
  printf '    http://localhost:%s\n' "\$PORT"
}

cmd_stop() {
  if running; then
    PID="\$(cat "\$PID_FILE")"
    kill "\$PID" 2>/dev/null || true
    i=0
    while kill -0 "\$PID" 2>/dev/null && [ "\$i" -lt 15 ]; do
      sleep 1
      i=\$((i + 1))
    done
    kill -9 "\$PID" 2>/dev/null || true
    rm -f "\$PID_FILE"
    say "Stopped"
  else
    rm -f "\$PID_FILE"
    say "Not running"
  fi
}

cmd_status() {
  if running; then
    say "Running (pid \$(cat "\$PID_FILE")) — http://localhost:\$PORT"
  else
    say "Not running"
  fi
}

cmd_logs() {
  [ -f "\$LOG_FILE" ] || die "no log yet at \$LOG_FILE"
  tail -n 100 -f "\$LOG_FILE"
}

cmd_update() {
  if [ ! -e "\$GIT_ROOT/.git" ]; then
    die "this installation has no git history — re-run the install.sh one-liner instead"
  fi
  WAS_RUNNING=0
  if running; then
    WAS_RUNNING=1
    cmd_stop
  fi
  say "Updating source (\$MESHWORK_REF)"
  cd "\$GIT_ROOT"
  git fetch --depth 1 origin "\$MESHWORK_REF"
  git reset --hard FETCH_HEAD
  say "Re-running setup (dependencies, .env, database)"
  cd "\$APP_DIR"
  ./setup.sh
  if [ "\$WAS_RUNNING" = "1" ] || [ -f .next/standalone/server.js ]; then
    say "Rebuilding the production server"
    "\$(pm)" run build
  fi
  if [ "\$WAS_RUNNING" = "1" ]; then
    cmd_start
  else
    say "Updated — start it with: meshwork start"
  fi
}

cmd_doctor() {
  ok=0
  fail=0
  check() {
    if [ "\$2" = "ok" ]; then
      printf '  \033[1;32m✓\033[0m %s\n' "\$1"
      ok=\$((ok + 1))
    else
      printf '  \033[1;31m✗\033[0m %s\n' "\$1"
      fail=\$((fail + 1))
    fi
  }
  say "Meshwork doctor"
  if command -v bun >/dev/null 2>&1; then
    check "runtime: bun \$(bun --version 2>/dev/null || echo present)" ok
  elif command -v node >/dev/null 2>&1; then
    check "runtime: node \$(node --version)" ok
  else
    check "runtime: none (bun 1.1+ or node 20+ required)" no
  fi
  if [ -f "\$APP_DIR/setup.sh" ]; then
    check "source: \$APP_DIR (\$MESHWORK_REF)" ok
  else
    check "source: missing — run install.sh" no
  fi
  if [ -d "\$APP_DIR/node_modules" ]; then
    check "dependencies installed" ok
  else
    check "dependencies missing (installed by meshwork start)" no
  fi
  if [ -f "\$APP_DIR/.env" ]; then
    check ".env present" ok
  else
    check ".env missing (created by meshwork start)" no
  fi
  if [ -f "\$APP_DIR/db/custom.db" ]; then
    check "database: \$(du -h "\$APP_DIR/db/custom.db" 2>/dev/null | cut -f1) (\$APP_DIR/db/custom.db)" ok
  else
    check "database: not created yet (created by meshwork start)" no
  fi
  if [ -f "\$APP_DIR/.next/standalone/server.js" ]; then
    check "production build present" ok
  else
    check "production build absent (built on first start)" no
  fi
  if running; then
    check "server: running (pid \$(cat "\$PID_FILE")) — http://localhost:\$PORT" ok
  else
    check "server: not running (meshwork start)" no
  fi
  printf '  %d ok, %d to do\n' "\$ok" "\$fail"
}

cmd_open() {
  URL="http://localhost:\$PORT"
  if command -v xdg-open >/dev/null 2>&1; then
    xdg-open "\$URL" >/dev/null 2>&1 || true
  elif command -v open >/dev/null 2>&1; then
    open "\$URL" || true
  else
    printf '%s\n' "\$URL"
  fi
}

case "\${1:-help}" in
  start) shift; cmd_start "\$@" ;;
  stop) cmd_stop ;;
  restart) shift; cmd_stop; cmd_start "\$@" ;;
  status) cmd_status ;;
  logs) cmd_logs ;;
  update) cmd_update ;;
  doctor) cmd_doctor ;;
  open) cmd_open ;;
  help | --help | -h) usage ;;
  *) die "unknown command: \$1 (try: meshwork help)" ;;
esac
LAUNCHER
chmod +x "$MESHWORK_BIN_DIR/meshwork"

rm -rf "$STAGE"

# --- done ------------------------------------------------------------------------
VERSION=""
if command -v node >/dev/null 2>&1; then
  VERSION="$(node -p "try{require('$APP_SRC/package.json').version||''}catch(e){''}" 2>/dev/null || true)"
fi
printf '\n'
if [ -n "$VERSION" ]; then
  say "Meshwork $VERSION ($MESHWORK_REF) installed at $MESHWORK_HOME"
else
  say "Meshwork ($MESHWORK_REF) installed at $MESHWORK_HOME"
fi
printf 'Start the workspace:\n'
printf '    meshwork start          # production build on port %s\n' "$MESHWORK_PORT"
printf '    meshwork start --dev    # or the dev server\n'
printf '\nOther commands: meshwork stop | status | logs | update | doctor | open\n'
case ":$PATH:" in
  *":$MESHWORK_BIN_DIR:"*) ;;
  *)
    printf '\nNote: %s is not in PATH. Add it with:\n    export PATH="%s:$PATH"\n' \
      "$MESHWORK_BIN_DIR" "$MESHWORK_BIN_DIR"
    ;;
esac
